/* ---------- 抽取:温度够、条件过、seen 去重;优先未看过的最高温度档 ---------- */
window.chatPage = function(id, G){
  if(!G || !window.CHATS) return null;
  const pool=CHATS[id]; if(!pool) return null;
  const period = G.day<=9?'early' : (G.day<=19?'mid':'late');
  const slice=pool[period]; if(!slice || !slice.length) return null;
  const b = (typeof bondOf==='function') ? bondOf(id) : 0;
  const seen = G.chatSeen = (G.chatSeen || {});
  const elig = slice.filter(it => (it.b||1)<=b && (!it.req || it.req(G)));
  if(!elig.length) return null;
  const keyOf = it => id+':'+period+':'+(it.b||1)+':'+(it.t||'').slice(0,10);
  const fresh = elig.filter(it => !seen[keyOf(it)]);
  const pick = (fresh.length ? fresh : elig)[(fresh.length ? fresh : elig).length-1];
  if(fresh.length) seen[keyOf(pick)] = 1;
  return { who:id, text:pick.t };
};

