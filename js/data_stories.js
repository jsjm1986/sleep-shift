/* ================= 工具:日程补丁 ================= */
function appendStory(n, ...items){
  const d = DAYS[n]; if(!d) return;
  const old = d.story;
  if(typeof old === 'function'){ d.story = (G)=>[...old(G), ...items]; }
  else if(old && old.twist){ d.storyAfter = [...(d.storyAfter||[]), ...items]; }
  else if(Array.isArray(old)){ d.story = [...old, ...items]; }
  else d.story = [...items];
}
function appendStoryAfter(n, ...items){
  const d = DAYS[n]; if(!d) return;
  d.storyAfter = [...(d.storyAfter||[]), ...items];
}
function appendNightNode(n, node){
  const d = DAYS[n]; if(!d || !d.night || !d.night.forced) return;
  d.night.forced.nodes.push(node);
}
